# Links the vault into %USERPROFILE%\.copilot so Copilot (Visual Studio) finds skills and hooks.
# Usage: powershell -NoProfile -ExecutionPolicy Bypass -File <vault>\install.ps1
$ErrorActionPreference = 'Stop'
$vaultRoot = $PSScriptRoot
$expectedRoot = Join-Path $env:USERPROFILE 'source\repos\Vault'
if ($vaultRoot -ne $expectedRoot) {
	Write-Warning "Vault is at '$vaultRoot', but the skill reads it from '$expectedRoot' (../Vault/ next to the opened solution). Move it there and run again."
}
$copilotDir = Join-Path $env:USERPROFILE '.copilot'
$skillsDir = Join-Path $copilotDir 'skills'

foreach ($dir in $copilotDir, $skillsDir) {
	if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
}

$links = [ordered]@{
	(Join-Path $copilotDir 'vault') = $vaultRoot
	(Join-Path $skillsDir 'vault')  = Join-Path $vaultRoot 'skills\vault'
	(Join-Path $copilotDir 'hooks') = Join-Path $vaultRoot '.github\hooks'
}

foreach ($link in $links.Keys) {
	$target = $links[$link]
	if (Test-Path $link) {
		$item = Get-Item $link
		if ($item.LinkType -eq 'Junction' -and ($item.Target | Select-Object -First 1) -eq $target) {
			Write-Host "OK (already linked): $link -> $target"
		} else {
			Write-Warning "Skipped: $link exists and is not a junction to $target. Rename it manually and run again."
		}
		continue
	}
	New-Item -ItemType Junction -Path $link -Target $target | Out-Null
	Write-Host "Linked: $link -> $target"
}

# Global git hooks (guardrails for protected branches) in every repository of this machine.
$gitHooksPath = (Join-Path $copilotDir 'vault\git-hooks') -replace '\\', '/'
$currentHooksPath = git config --global --get core.hooksPath
if ($currentHooksPath -and $currentHooksPath -ne $gitHooksPath) {
	Write-Warning "core.hooksPath already set to '$currentHooksPath'. Not changed; set it to '$gitHooksPath' manually if desired."
} else {
	git config --global core.hooksPath $gitHooksPath
	Write-Host "Git hooks: core.hooksPath = $gitHooksPath"
}

# Monitor: modal alert when a new Visual Studio starts and the hooks are not working. Starts at logon (HKCU Run, no admin).
# The launcher lives outside the vault so a missing or moved vault still raises an alert.
$launcher = Join-Path $copilotDir 'vault-monitor-start.ps1'
$launcherContent = @'
# Generated by install.ps1 (Vault). Starts vault-monitor.ps1 or alerts if it is missing.
$monitor = '__MONITOR__'
if (Test-Path -LiteralPath $monitor) { & $monitor; exit }
Add-Type -AssemblyName System.Windows.Forms
$owner = New-Object System.Windows.Forms.Form -Property @{ TopMost = $true }
[void][System.Windows.Forms.MessageBox]::Show($owner, "VAULT HOOKS: FALHA - monitor do Vault nao encontrado: $monitor`n`nOs hooks do Vault podem nao estar funcionando. Clone o Vault em source\repos e rode install.ps1.", 'Vault - hooks', 'OK', 'Error')
'@
$launcherContent = $launcherContent.Replace('__MONITOR__', ((Join-Path $vaultRoot 'vault-monitor.ps1') -replace "'", "''"))
Set-Content -LiteralPath $launcher -Value $launcherContent -Encoding UTF8
$runValue = "powershell.exe -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$launcher`""
Set-ItemProperty -Path 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run' -Name 'VaultHooksMonitor' -Value $runValue
Start-Process powershell.exe -ArgumentList "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$launcher`""
Write-Host "Monitor: $launcher (logon: HKCU Run 'VaultHooksMonitor'), started."

# Final check: the hooks must be working.
$checkResult = & (Join-Path $vaultRoot 'check-hooks.ps1')
if ($LASTEXITCODE -eq 0) { Write-Host $checkResult } else { Write-Warning $checkResult }
